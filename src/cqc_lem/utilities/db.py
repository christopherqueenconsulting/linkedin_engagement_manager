"""The stable name for every database symbol LEM has. Imports and `__all__` — nothing else.

There is no SQL here any more (issue #1614). Each aggregate's statements live in
`cqc_lem.platform.db.repositories.<aggregate>`, the connection and cursor in
`platform/db/connection.py`, the enums in `platform/db/enums.py`, and what more than one aggregate
needs in `platform/db/shared.py`. This module re-exports all of it, because ~2,400 call sites say
`from cqc_lem.utilities.db import X` and the facade is the name that does not move.

Two contracts followed the code out of here and still hold at the new addresses:

* **Readers fail SOFT.** A `mysql.connector.Error` is logged and turned into the empty answer for
  that shape (None / [] / 0 / False), so a database blip degrades one feature instead of raising
  through a Celery task or an API handler. Where that default would be the dangerous answer the
  function fails the other way and says so — `has_received_lead_magnet` returns True on error so a
  fault never double-DMs, and `user_owns_posts` raises `OwnershipUnprovable` rather than answer an
  authorisation question it could not run (issue #914).
* **Secrets are sealed and unsealed in the repositories and nowhere else** (issue #745): `li_at` and
  the other cookie values, the OAuth tokens and the stored password, keyed per user+column off
  `LEM_SECRET_KEY` with the `SECRET_FIELD_*` constants as AAD. Renaming one of those constants
  orphans every row already written under it, and a value that will not decrypt reads as None
  rather than as ciphertext.

**Patch targets are the one place this facade is the wrong name.** A re-export is a SECOND binding,
so patching `cqc_lem.utilities.db.X` is only seen by callers that read X through here. A caller
sitting in the SAME repository module as X reads it from that module's globals and never consults
this one — patch it where it now LIVES. `tests/unit/platform/db/test_connection_seam.py` derives
that hazard set per module and fails the build on it.
"""

